<#
.SYNOPSIS
Downloads or locates and verifies the DLH.io Aloha POS agent installer.

.DESCRIPTION
Checks the installer SHA256 and Authenticode signature before launching Setup.
Run from an elevated PowerShell prompt.

.EXAMPLE
.\Install-DlhAgentAlohaPos.ps1 -InstallerUrl 'https://<account>.blob.core.windows.net/<container>/<installer>.exe?<SAS-token>' -ExpectedSha256 '<64-character SHA256>'

.EXAMPLE
.\Install-DlhAgentAlohaPos.ps1 -InstallerPath 'C:\Downloads\dlh-agent-for-aloha-pos-installer.exe' -ExpectedSha256 '<64-character SHA256>'
#>
#Requires -RunAsAdministrator
[CmdletBinding(DefaultParameterSetName = 'Url')]
param(
    [Parameter(Mandatory = $true, ParameterSetName = 'Url')]
    [ValidatePattern('(?i)^https://')]
    [string]$InstallerUrl,

    [Parameter(Mandatory = $true, ParameterSetName = 'Path')]
    [ValidateScript({ Test-Path -LiteralPath $_ -PathType Leaf })]
    [string]$InstallerPath,

    [Parameter(Mandatory = $true)]
    [string]$ExpectedSha256,

    [string]$LogPath = (Join-Path $env:ProgramData (
        'DLH.io\install-logs\aloha-pos-setup-{0}.log' -f (Get-Date -Format 'yyyyMMdd-HHmmss')
    ))
)

$ErrorActionPreference = 'Stop'
$ProgressPreference = 'SilentlyContinue'
$file = $null

if ($PSCmdlet.ParameterSetName -eq 'Url') {
    [Net.ServicePointManager]::SecurityProtocol =
        [Net.ServicePointManager]::SecurityProtocol -bor [Net.SecurityProtocolType]::Tls12
    $file = Join-Path ([System.IO.Path]::GetTempPath()) (
        'dlh-agent-aloha-pos-{0}.exe' -f [System.IO.Path]::GetRandomFileName()
    )
    try {
        Invoke-WebRequest -Uri $InstallerUrl -UseBasicParsing -OutFile $file
    } catch {
        Write-Output "Installer download failed: $($_.Exception.Message)"
        exit 10
    }
} else {
    $file = $InstallerPath
}

try {
    $actualSha256 = (Get-FileHash -LiteralPath $file -Algorithm SHA256).Hash.Trim()
} catch {
    Write-Output "Unable to calculate installer SHA256: $($_.Exception.Message)"
    exit 11
}
if ($actualSha256 -ine $ExpectedSha256.Trim()) {
    Write-Output "Installer SHA256 mismatch. Expected $($ExpectedSha256.Trim()), got $actualSha256."
    exit 11
}

try {
    $signature = Get-AuthenticodeSignature -FilePath $file
} catch {
    Write-Output "Unable to read installer signature: $($_.Exception.Message)"
    exit 12
}
if ($signature.Status -ne 'Valid') {
    Write-Output "Installer signature is not valid: $($signature.Status)."
    exit 12
}

$signerCertificate = $signature.SignerCertificate
if ($null -eq $signerCertificate) {
    Write-Output 'Unexpected installer signer: signer certificate is missing.'
    exit 13
}
$signerName = $signerCertificate.GetNameInfo(
    [System.Security.Cryptography.X509Certificates.X509NameType]::SimpleName,
    $false
)
if ($signerName -ne 'DLH.io (AICG, Inc.)' -or
    $signerCertificate.Issuer -notlike '*Microsoft ID Verified*') {
    Write-Output "Unexpected installer signer or issuer: signer='$signerName', issuer='$($signerCertificate.Issuer)'."
    exit 13
}

Unblock-File -LiteralPath $file
$logDirectory = Split-Path -Parent $LogPath
if ([string]::IsNullOrWhiteSpace($logDirectory)) {
    $logDirectory = (Get-Location).Path
}
New-Item -ItemType Directory -Force -Path $logDirectory | Out-Null

$setup = Start-Process -FilePath $file -ArgumentList @(
    '/VERYSILENT',
    '/SUPPRESSMSGBOXES',
    '/NORESTART',
    "/LOG=`"$LogPath`""
) -Wait -PassThru
exit $setup.ExitCode

